//go:build linux && !android

package fstools

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"os"
	"runtime"
	"strconv"
	"strings"

	"golang.org/x/sys/unix"
)

type linuxPendingReplace struct {
	*linuxPendingCreate
	staging      string
	beforeCommit func() error
}

func newPendingReplace(root *os.Root, filename string, beforeCommit func() error) (pendingCreation, error) {
	pending, err := newPendingCreate(root, filename)
	if err != nil {
		return nil, err
	}
	p := &linuxPendingReplace{linuxPendingCreate: pending.(*linuxPendingCreate), beforeCommit: beforeCommit}
	if err := p.checkTarget(); err != nil {
		p.Close()
		return nil, err
	}
	return p, nil
}
func (p *linuxPendingReplace) checkTarget() error {
	var st unix.Stat_t
	err := unix.Fstatat(int(p.parent.Fd()), p.name, &st, unix.AT_SYMLINK_NOFOLLOW)
	runtime.KeepAlive(p)
	if errors.Is(err, unix.ENOENT) {
		return nil
	}
	if err != nil {
		return err
	}
	if st.Mode&unix.S_IFMT != unix.S_IFREG {
		return errors.New("replacement target is not regular")
	}
	return nil
}
func (p *linuxPendingReplace) Publish() error {
	// This observation is not CAS. A subsequent name change may be replaced.
	if err := p.checkTarget(); err != nil {
		return err
	}
	// A complete anonymous inode is linked only immediately before rename. The
	// host must prevent malicious writers from manipulating this staging name.
	for attempt := 0; attempt < 8; attempt++ {
		var random [16]byte
		if _, err := rand.Read(random[:]); err != nil {
			return err
		}
		name := ".pigo-replace-" + hex.EncodeToString(random[:])
		if name == p.name {
			continue
		}
		err := p.publishStaged(name)
		if errors.Is(err, unix.EEXIST) && p.staging == "" {
			continue
		}
		return err
	}
	return errors.New("replacement staging name collisions")
}

// name is generated by the host, never supplied by the model.
func (p *linuxPendingReplace) publishStaged(name string) error {
	if name == "" || name == "." || name == ".." || name == p.name || strings.ContainsAny(name, "/\x00") {
		return errors.New("invalid staging basename")
	}
	err := unix.Linkat(int(p.proc.Fd()), strconv.Itoa(int(p.File.Fd())), int(p.parent.Fd()), name, unix.AT_SYMLINK_FOLLOW)
	runtime.KeepAlive(p)
	if err != nil {
		return err
	}
	p.staging = name
	if p.beforeCommit != nil {
		if err := p.beforeCommit(); err != nil {
			return err
		}
	}
	err = unix.Renameat(int(p.parent.Fd()), name, int(p.parent.Fd()), p.name)
	runtime.KeepAlive(p)
	if err == nil {
		p.staging = ""
	}
	return err
}
func (p *linuxPendingReplace) Close() error {
	var err error
	if p.staging != "" {
		err = unix.Unlinkat(int(p.parent.Fd()), p.staging, 0)
		runtime.KeepAlive(p)
		p.staging = ""
	}
	return errors.Join(err, p.linuxPendingCreate.Close())
}
